import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
// Serialize the original browser source before bundling. This keeps esbuild's
// Worker-only helper functions out of the script served to the browser.
const source=readFileSync(new URL('../src/portal-client.js',import.meta.url),'utf8').replace(/^export /m,'');
const script='(() => {\n'+source+'\nportalClient();\n})();';
mkdirSync(new URL('../src/generated/',import.meta.url),{recursive:true});
writeFileSync(new URL('../src/generated/portal-client-source.js',import.meta.url),'// Generated by scripts/build-client.js. Do not edit directly.\nexport const clientScript = '+JSON.stringify(script)+';\n');

const {mapClient}=await import('../src/event-map-client.js');
writeFileSync(new URL('../src/generated/event-map-client-source.js',import.meta.url),'export const eventMapClientScript = '+JSON.stringify('('+mapClient.toString()+')();')+';\n');
